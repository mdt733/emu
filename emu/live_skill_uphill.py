"""Fixed uphill practice/reference cohorts in the existing Academy.

No extra world, extra mesh, actor input or invented support. Exact single
seam is generated by the same physical prism profile as frozen exams.
Reference/practice have identical task and geometry distributions. Only
practice can receive optional once-per-life prerequisite credit.
"""
UP_HEIGHTS_M=(.004,.008,.012,.020,.028,.032)
UP_CLIFF_HEIGHTS_M=(.020,.028,.029,.030,.031,.032)


def uphill_heights(profile='ladder'):
    if profile=='ladder': return UP_HEIGHTS_M
    if profile=='cliff': return UP_CLIFF_HEIGHTS_M
    raise ValueError('Unknown uphill lesson profile')

UP_VX=.16
UP_APPROACH_M=.22
UP_FRAMES=350
UP_SENSOR_SCALE=1.
UP_STAGE_NAMES=("none","first_support","bilateral","traversal")


def uphill_assignment(jax,xp,keys,academy,mix,reference_share,practice_share,weights=None):
    if reference_share<=0. and practice_share<=0.:
        return xp.full(academy.shape,-1,dtype=xp.int32)
    draw=jax.vmap(lambda k:jax.random.uniform(jax.random.fold_in(k,50611),()))(keys)
    case=jax.vmap(lambda k:jax.random.randint(jax.random.fold_in(k,50612),(),0,6))(keys)
    practice_case=case
    if practice_share>0.:
        # Uniform and adaptive arms use the SAME practice RNG stream.
        # Before the first teacher decision their assignments are exact matches.
        weights=xp.full((6,),1./6,dtype=xp.float32) if weights is None else weights
        logits=xp.log(xp.maximum(weights,1e-30))
        practice_case=jax.vmap(lambda k:jax.random.categorical(
            jax.random.fold_in(k,50613),logits))(keys)
    eligible=academy & (mix>=.999999)
    return xp.where(eligible & (draw<reference_share),case,
        xp.where(eligible & (draw>=reference_share) &
                 (draw<reference_share+practice_share),6+practice_case,-1)).astype(xp.int32)


def assigned_height(xp,ids,heights=UP_HEIGHTS_M):
    return xp.where(ids>=0,xp.asarray(heights,dtype=xp.float32)[xp.mod(xp.maximum(ids,0),6)],0.)


def uphill_task(xp,task,T,ids,vx_hi,phase_gain):
    from .environment import command_phase_rate
    active=ids>=0
    for name in ("vy","yaw","height","pitch","roll","resilience","birth_resilience_d","field_taught","regime"):
        col=getattr(T,name)
        task=task.at[:,col].set(xp.where(active,0.,task[:,col]))
    task=task.at[:,T.vx].set(xp.where(active,UP_VX,task[:,T.vx]))
    task=task.at[:,T.sensor_scale].set(xp.where(active,UP_SENSOR_SCALE,task[:,T.sensor_scale]))
    task=task.at[:,T.step_height].set(xp.where(active,.012,task[:,T.step_height]))
    phase=command_phase_rate(xp.full(ids.shape,UP_VX),xp.zeros(ids.shape),vx_hi,phase_gain,xp.ones(ids.shape))
    return task.at[:,T.phase_rate].set(xp.where(active,phase,task[:,T.phase_rate]))


def prerequisite_payment(xp,ids,stage,previous_feet,next_feet,previous_traversed,next_traversed,failed):
    """Optional bounded bonus: only newly earned real physical milestones.

    No repeat payments, no positive payment on failed frame, no teacher
    credit on reference or ordinary worlds. Stage is a static research
    choice; automatic stage allocation is a subsequent experiment.
    """
    if stage=="none":
        return xp.zeros(ids.shape,dtype=xp.float32)
    before=xp.sum(previous_feet,axis=1)
    after=xp.sum(next_feet,axis=1)
    if stage=="first_support":
        new=(before==0)&(after>=1)
    elif stage=="bilateral":
        new=(before<2)&(after==2)
    elif stage=="traversal":
        new=next_traversed & ~previous_traversed
    else:
        raise ValueError("Unknown uphill prerequisite stage")
    return 4.*(new & (ids>=6) & ~failed).astype(xp.float32)


def birth_credit(xp,ids,stages,bonuses):
    case=xp.mod(xp.maximum(ids,0),6)
    return (xp.where(ids>=6,stages[case],0).astype(xp.int32),
            xp.where(ids>=6,bonuses[case],0.))


def assigned_prerequisite_payment(xp,ids,stage,bonus,previous_feet,next_feet,
                                 previous_traversed,next_traversed,failed):
    before=xp.sum(previous_feet,axis=1); after=xp.sum(next_feet,axis=1)
    new=((stage==1)&(before==0)&(after>=1)) | (
         (stage==2)&(before<2)&(after==2)) | (
         (stage==3)&next_traversed&~previous_traversed)
    return xp.where(new & (ids>=6) & ~failed,bonus,0.)
